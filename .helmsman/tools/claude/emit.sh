#!/usr/bin/env bash
# Give Claude Code the same rules and skills Cursor reads from .cursor/.
#
#   .cursor/rules/<name>.mdc  ->  .claude/rules/<name>.md
#     alwaysApply: true        no frontmatter, so Claude loads it every session
#     globs                    `paths:` with the same globs, loaded when a matching file is read or edited
#     neither                  not emitted; the skills that need it read the .mdc by path
#   .cursor/skills/<name>/    ->  .claude/skills/<name>, a relative symlink
#   AGENTS.md                 ->  CLAUDE.md with `@AGENTS.md`, written only when no CLAUDE.md exists
#
# Claude reads a rule's `paths` only. It has no rule chosen by description, and a commit message or a
# pull request body is not a file it reads, so the rules in ALWAYS load every session.
# A rule or skill folder already in .claude/ without the generated marker is the repo's own. It is left alone.
#
# --check fails when .claude/ is not this output. It writes nothing.
set -euo pipefail

mode="write"
case "${1:-}" in
  "") mode="write" ;;
  --check) mode="check" ;;
  -h | --help)
    echo "helmsman: emit.sh [--check]"
    echo "  .helmsman/tools/claude/emit.sh          write .claude/rules, .claude/skills, and CLAUDE.md"
    exit 0
    ;;
  *)
    echo "helmsman: emit.sh [--check]" >&2
    exit 2
    ;;
esac

root="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
cd "$root"

if [[ ! -d .cursor/rules && ! -d .cursor/skills ]]; then
  echo "helmsman: no .cursor/rules or .cursor/skills. Claude files not emitted."
  exit 0
fi

MODE="$mode" ALWAYS="helmsman-writing" python3 - << 'PY'
import os
import sys
from pathlib import Path

mode = os.environ["MODE"]
always = set(os.environ["ALWAYS"].split())
marker = "<!-- Generated by .helmsman/tools/claude/emit.sh from {src}. Edit the source, then run the script. -->"
problems = []


def frontmatter(text):
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return {}, text
    for end in range(1, len(lines)):
        if lines[end].strip() == "---":
            break
    else:
        return {}, text
    meta = {"globs": []}
    key = None
    for line in lines[1:end]:
        stripped = line.strip()
        if line.startswith((" ", "\t")) and stripped.startswith("- ") and key == "globs":
            meta["globs"].append(stripped[2:].strip().strip("\"'"))
            continue
        if ":" in line and not line.startswith((" ", "\t")):
            key, _, value = line.partition(":")
            key = key.strip()
            value = value.strip()
            if key == "globs" and value:
                meta["globs"].extend(g.strip().strip("\"'") for g in value.split(",") if g.strip())
            elif key == "alwaysApply":
                meta["alwaysApply"] = value.lower() == "true"
    body = "\n".join(lines[end + 1 :]).lstrip("\n")
    return meta, body


def rule_text(src, meta, body):
    head = marker.format(src=src)
    if meta.get("alwaysApply") or Path(src).stem in always:
        return f"{head}\n\n{body}"
    paths = "".join(f'  - "{g}"\n' for g in meta["globs"])
    return f"---\npaths:\n{paths}---\n\n{head}\n\n{body}"


def generated(path):
    try:
        return "Generated by .helmsman/tools/claude/emit.sh" in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def put(path, text):
    if path.is_symlink() or (path.exists() and not generated(path)):
        print(f"helmsman: {path} is the repo's own. Left alone.")
        return
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == text:
        return
    if mode == "check":
        problems.append(f"{path} is not what emit.sh writes")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


expected_rules = set()
for src in sorted(Path(".cursor/rules").glob("*.mdc")):
    meta, body = frontmatter(src.read_text(encoding="utf-8"))
    if not (meta.get("alwaysApply") or meta.get("globs") or src.stem in always):
        continue
    dest = Path(".claude/rules") / f"{src.stem}.md"
    expected_rules.add(dest)
    put(dest, rule_text(src.as_posix(), meta, body))

for dest in sorted(Path(".claude/rules").glob("*.md")):
    if dest not in expected_rules and not dest.is_symlink() and generated(dest):
        if mode == "check":
            problems.append(f"{dest} has no source in .cursor/rules")
        else:
            dest.unlink()

expected_links = set()
for src in sorted(p for p in Path(".cursor/skills").glob("*") if (p / "SKILL.md").is_file()):
    link = Path(".claude/skills") / src.name
    target = Path("../../.cursor/skills") / src.name
    expected_links.add(link)
    if link.is_symlink():
        if Path(os.readlink(link)) == target:
            continue
        print(f"helmsman: {link} points somewhere else. Left alone.")
        continue
    if link.exists():
        print(f"helmsman: {link} is the repo's own. Left alone.")
        continue
    if mode == "check":
        problems.append(f"{link} is missing")
        continue
    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(target, target_is_directory=True)

skills_dir = Path(".claude/skills")
if skills_dir.is_dir():
    for link in sorted(skills_dir.iterdir()):
        if link.is_symlink() and link not in expected_links:
            target = os.readlink(link)
            if target.startswith("../../.cursor/skills/"):
                if mode == "check":
                    problems.append(f"{link} has no source in .cursor/skills")
                else:
                    link.unlink()

agents = Path("AGENTS.md")
claude = Path("CLAUDE.md")
dot_claude = Path(".claude/CLAUDE.md")
if agents.is_file():
    if claude.exists() or dot_claude.exists():
        own = claude if claude.exists() else dot_claude
        if "@AGENTS.md" not in own.read_text(encoding="utf-8"):
            problems.append(f"{own} does not import @AGENTS.md, so Claude never reads AGENTS.md")
    elif mode == "check":
        problems.append("CLAUDE.md is missing. Claude reads AGENTS.md through it")
    else:
        claude.write_text("@AGENTS.md\n", encoding="utf-8")

if problems:
    for problem in problems:
        print(f"helmsman: {problem}. Run .helmsman/tools/claude/emit.sh.", file=sys.stderr)
    sys.exit(1)

if mode == "check":
    print("helmsman: .claude matches emit.sh.")
else:
    print(f"helmsman: wrote {len(expected_rules)} Claude rules and {len(expected_links)} skill links.")
PY
