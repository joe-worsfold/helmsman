#!/usr/bin/env bash
# Give Claude Code the same rules and skills Cursor reads from .cursor/.
#
#   .cursor/rules/<name>.mdc  ->  .claude/rules/<name>.md
#     alwaysApply: true        no frontmatter, so Claude loads it every session
#     globs                    `paths:` with the same globs, loaded when a matching file is read or edited
#     neither                  not emitted; the skills that need it read the .mdc by path
#   .cursor/skills/<name>/    ->  .claude/skills/<name>, a relative symlink
#   AGENTS.md                 ->  CLAUDE.md with `@AGENTS.md`, written only when no CLAUDE.md exists
#
# Claude reads a rule's `paths` only. It has no rule chosen by description, and a commit message or a
# pull request body is not a file it reads, so the rules in ALWAYS load every session.
# A rule or skill folder already in .claude/ without the generated marker is the repo's own. It is left alone.
#
# --check fails when .claude/ is not this output. It writes nothing.
# --context prints the rules for the helmsman plugin's SessionStart hook: the always-on rules in
# full, and a path list for the file-scoped ones. It reads rules from this script's own checkout and
# skips any rule the project already has in .claude/rules/.
set -euo pipefail

mode="write"
case "${1:-}" in
  "") mode="write" ;;
  --check) mode="check" ;;
  --context) mode="context" ;;
  -h | --help)
    echo "helmsman: emit.sh [--check|--context]"
    echo "  .helmsman/tools/claude/emit.sh          write .claude/rules, .claude/skills, and CLAUDE.md"
    exit 0
    ;;
  *)
    echo "helmsman: emit.sh [--check|--context]" >&2
    exit 2
    ;;
esac

project="${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null || pwd)}"
if [[ "$mode" == "context" ]]; then
  root="$(cd "$(dirname "$0")/../../.." && pwd)"
else
  root="$project"
fi
cd "$root"

if [[ ! -d .cursor/rules && ! -d .cursor/skills ]]; then
  echo "helmsman: no .cursor/rules or .cursor/skills. Claude files not emitted."
  exit 0
fi

MODE="$mode" PROJECT="$project" ALWAYS="helmsman-writing" python3 - << 'PY'
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

mode = os.environ["MODE"]
always = set(os.environ["ALWAYS"].split())
marker = "<!-- Generated by .helmsman/tools/claude/emit.sh from {src}. Edit the source, then run the script. -->"
problems = []


def frontmatter(text):
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return {}, text
    for end in range(1, len(lines)):
        if lines[end].strip() == "---":
            break
    else:
        return {}, text
    meta = {"globs": []}
    key = None
    for line in lines[1:end]:
        stripped = line.strip()
        if line.startswith((" ", "\t")) and stripped.startswith("- ") and key == "globs":
            meta["globs"].append(stripped[2:].strip().strip("\"'"))
            continue
        if ":" in line and not line.startswith((" ", "\t")):
            key, _, value = line.partition(":")
            key = key.strip()
            value = value.strip()
            if key == "globs" and value:
                meta["globs"].extend(g.strip().strip("\"'") for g in value.split(",") if g.strip())
            elif key == "alwaysApply":
                meta["alwaysApply"] = value.lower() == "true"
    body = "\n".join(lines[end + 1 :]).lstrip("\n")
    return meta, body


def rule_text(src, meta, body):
    head = marker.format(src=src)
    if meta.get("alwaysApply") or Path(src).stem in always:
        return f"{head}\n\n{body}"
    paths = "".join(f'  - "{g}"\n' for g in meta["globs"])
    return f"---\npaths:\n{paths}---\n\n{head}\n\n{body}"


def generated(path):
    try:
        return "Generated by .helmsman/tools/claude/emit.sh" in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def put(path, text):
    if path.is_symlink() or (path.exists() and not generated(path)):
        print(f"helmsman: {path} is the repo's own. Left alone.")
        return
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == text:
        return
    if mode == "check":
        problems.append(f"{path} is not what emit.sh writes")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


if mode == "context":
    project_rules = Path(os.environ["PROJECT"]) / ".claude/rules"
    scoped = []
    for src in sorted(Path(".cursor/rules").glob("*.mdc")):
        if (project_rules / f"{src.stem}.md").exists():
            continue
        meta, body = frontmatter(src.read_text(encoding="utf-8"))
        if meta.get("alwaysApply") or src.stem in always:
            print(f"<!-- helmsman plugin rule: {src.stem} -->\n{body.rstrip()}\n")
        elif meta.get("globs"):
            scoped.append(f"- {', '.join(meta['globs'])}: read {src.resolve()}")
    if scoped:
        print("# Helmsman file rules\n\nBefore you edit a file matching a pattern below, read that rule.\n")
        print("\n".join(scoped))
    sys.exit(0)


def plugin_enabled():
    try:
        settings = json.loads(Path(".claude/settings.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return False
    return settings.get("enabledPlugins", {}).get("helmsman@helmsman") is True


# The helmsman plugin ships the rules and skills, so a generated copy would load them twice.
plugin = plugin_enabled()
stale = "is a generated copy the helmsman plugin replaces" if plugin else "has no source in .cursor"

expected_rules = set()
for src in [] if plugin else sorted(Path(".cursor/rules").glob("*.mdc")):
    meta, body = frontmatter(src.read_text(encoding="utf-8"))
    if not (meta.get("alwaysApply") or meta.get("globs") or src.stem in always):
        continue
    dest = Path(".claude/rules") / f"{src.stem}.md"
    expected_rules.add(dest)
    put(dest, rule_text(src.as_posix(), meta, body))

for dest in sorted(Path(".claude/rules").glob("*.md")):
    if dest not in expected_rules and not dest.is_symlink() and generated(dest):
        if mode == "check":
            problems.append(f"{dest} {stale}")
        else:
            dest.unlink()

# Without symlinks (git core.symlinks=false, common on Windows) a link checks out as a text
# file holding its target, and Claude Code cannot read it. Those checkouts get a marked copy.
COPY_MARK = ".helmsman-copy"


def symlinks_work():
    out = subprocess.run(["git", "config", "--get", "core.symlinks"], capture_output=True, text=True)
    return out.stdout.strip().lower() != "false"


def link_stub(path, target):
    if not path.is_file() or path.is_symlink():
        return False
    try:
        return path.read_text(encoding="utf-8").strip() == target.as_posix()
    except (OSError, UnicodeDecodeError):
        return False


def our_copy(path):
    return path.is_dir() and not path.is_symlink() and (path / COPY_MARK).is_file()


def tree(path):
    return {
        f.relative_to(path).as_posix(): f.read_bytes()
        for f in sorted(path.rglob("*"))
        if f.is_file() and f.name != COPY_MARK
    }


def remove(path):
    if path.is_dir() and not path.is_symlink():
        shutil.rmtree(path)
    else:
        path.unlink()


def place(src, link, target):
    link.parent.mkdir(parents=True, exist_ok=True)
    if use_links:
        link.symlink_to(target, target_is_directory=True)
        return
    shutil.copytree(src, link)
    (link / COPY_MARK).write_text("Generated by .helmsman/tools/claude/emit.sh from .cursor/skills. Edit the source, then run the script.\n", encoding="utf-8")


use_links = symlinks_work()
expected_links = set()
for src in [] if plugin else sorted(p for p in Path(".cursor/skills").glob("*") if (p / "SKILL.md").is_file()):
    link = Path(".claude/skills") / src.name
    target = Path("../../.cursor/skills") / src.name
    expected_links.add(link)
    if link.is_symlink() and use_links:
        if Path(os.readlink(link)) == target:
            continue
        print(f"helmsman: {link} points somewhere else. Left alone.")
        continue
    if our_copy(link) and not use_links and tree(link) == tree(src):
        continue
    ours = link.is_symlink() or our_copy(link) or link_stub(link, target)
    if link.exists() and not ours:
        print(f"helmsman: {link} is the repo's own. Left alone.")
        continue
    if mode == "check":
        problems.append(f"{link} is not what emit.sh writes" if ours else f"{link} is missing")
        continue
    if ours:
        remove(link)
    place(src, link, target)

skills_dir = Path(".claude/skills")
if skills_dir.is_dir():
    for link in sorted(skills_dir.iterdir()):
        if link in expected_links:
            continue
        target = Path("../../.cursor/skills") / link.name
        linked = link.is_symlink() and os.readlink(link).startswith("../../.cursor/skills/")
        if linked or our_copy(link) or link_stub(link, target):
            if mode == "check":
                problems.append(f"{link} {stale}")
            else:
                remove(link)

agents = Path("AGENTS.md")
claude = Path("CLAUDE.md")
dot_claude = Path(".claude/CLAUDE.md")
if agents.is_file():
    if claude.exists() or dot_claude.exists():
        own = claude if claude.exists() else dot_claude
        if not re.search(r"(^|\s)@(\./)?AGENTS\.md\b", own.read_text(encoding="utf-8")):
            problems.append(f"{own} does not import @AGENTS.md, so Claude never reads AGENTS.md")
    elif mode == "check":
        problems.append("CLAUDE.md is missing. Claude reads AGENTS.md through it")
    else:
        claude.write_text("@AGENTS.md\n", encoding="utf-8")

if problems:
    for problem in problems:
        print(f"helmsman: {problem}. Run .helmsman/tools/claude/emit.sh.", file=sys.stderr)
    sys.exit(1)

if mode == "check":
    print("helmsman: .claude matches emit.sh.")
else:
    print(f"helmsman: wrote {len(expected_rules)} Claude rules and {len(expected_links)} skill links.")
PY
